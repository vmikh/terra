export function estimatedAt(year: number) {
  const e = epochAt(year),
    pop = populationAt(year);
  return {
    temperature: interpolate(temperature, year),
    oxygen: interpolate(oxygen, year),
    ocean: interpolate(ocean, year),
    population: pop ?? interpolate(population, year),
    co2: interpolate(carbon, year),
    inferredPopulation: pop === null,
    inferredTemperature: e.temp === '—',
    inferredOxygen: e.oxygen === '—',
  };
}
