import { epochAt, populationAt, NOW, MIN, MAX } from './epochs';
export type Knot = readonly [number, number];
/** Educational interpolation only; all output from these knots is AI reconstruction. */
export function interpolate(knots: readonly Knot[], year: number) {
  if (year <= knots[0][0]) return knots[0][1];
  for (let i = 1; i < knots.length; i++) {
    if (year <= knots[i][0]) {
      const [x, a] = knots[i - 1],
        [z, b] = knots[i];
      return a + ((b - a) * (year - x)) / (z - x);
    }
  }
  return knots.at(-1)![1];
}
